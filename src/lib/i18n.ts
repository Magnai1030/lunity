/** Fills store settings into copy, e.g. "{days}" → settings.deliveryDays, across every string. */
function withSettings<T>(v: T): T {
  if (typeof v === "string") return v.replace(/\{days\}/g, String(settings.deliveryDays)) as T;
  if (Array.isArray(v)) return v.map(withSettings) as T;
  if (v && typeof v === "object") return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, withSettings(x)])) as T;
  return v;
}

