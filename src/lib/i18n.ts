/** Replace `{key}` placeholders. */
export function fmt(s: string, vars: Record<string, string | number>) {
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

const priceFmt = new Intl.NumberFormat("en-US");
export const formatPrice = (n: number) => `₮${priceFmt.format(n)}`;
/** Shipping row value: "Free" when there is no fee. */
export const formatShipping = (fee: number, t: Dict) => (fee ? formatPrice(fee) : t.free);

export function formatDate(iso: string, lang: Lang) {
  const d = new Date(`${iso}T00:00:00`);
  return new Intl.DateTimeFormat(lang === "mn" ? "mn-MN" : "en-US", { month: "short", day: "numeric", year: "numeric" }).format(d);
}

/** ISO date `n` days after `iso`. */
export function addDays(iso: string, n: number) {
  const d = new Date(`${iso}T00:00:00`);
  d.setDate(d.getDate() + n);
  return d.toLocaleDateString("sv");
}

/** "by Nov 18, 2026" when today is known (client), "within 20 days" while prerendering. */
export function deliveryWhen(days: number, today: string | null, t: Dict, lang: Lang) {
  return today ? fmt(t.when.by, { d: formatDate(addDays(today, days), lang) }) : fmt(t.when.within, { n: days });
}

export function formatDateShort(iso: string, lang: Lang) {
  const d = new Date(`${iso}T00:00:00`);
  return new Intl.DateTimeFormat(lang === "mn" ? "mn-MN" : "en-US", { month: "short", day: "numeric" }).format(d);
}
